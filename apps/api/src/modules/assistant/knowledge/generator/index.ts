import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { scanErrorCodes, type ErrorCodeRow } from './scan-error-codes';
import { scanPages, type PageRow } from './scan-pages';
import type { Console } from './scan-pages';
import { scanInternalDocs, scanPortalText, scanSettings, type TextRow } from './scan-help-text';

/**
 * The committed indexes under `knowledge/generated/`. `render()` is the
 * ONE place that turns a repository checkout into their exact bytes: the
 * npm script writes them, and the staleness spec calls it again and
 * compares. Same function, so the two cannot disagree about formatting.
 */
export const REGENERATE_COMMAND = 'pnpm --filter @skydrop/api assistant:knowledge';

const HEADER = (what: string): string =>
  `// @generated by \`${REGENERATE_COMMAND}\` — do not edit by hand.\n// ${what}\n`;

function rows(name: string, type: string, data: readonly unknown[]): string {
  const lines = data.map((r) => `  ${JSON.stringify(r)},`);
  return `export const ${name}: ${type} = [\n${lines.join('\n')}\n];\n`;
}

export interface GeneratedFiles {
  /** Path relative to `knowledge/generated/`. */
  readonly [file: string]: string;
}

export function render(root: string): GeneratedFiles {
  const codes: ErrorCodeRow[] = scanErrorCodes(join(root, 'apps/api/src'));
  const pages = scanPages(root);
  const portal = scanPortalText(root);
  const settings: TextRow[] = scanSettings(root);
  const docs: TextRow[] = scanInternalDocs(root);

  const pageBlocks = (Object.keys(pages) as Console[])
    .map(
      (c) =>
        `export const PAGES_${c.toUpperCase()}: ReadonlyArray<PageRow> = [\n${(pages[c] as PageRow[]).map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n];\n`,
    )
    .join('\n');

  return {
    'error-codes.ts':
      HEADER("Every `code: 'X'` thrown in apps/api/src: [code, domain (module folder), message].") +
      rows('ERROR_CODES', 'ReadonlyArray<readonly [string, string, string | null]>', codes),
    'page-map.ts':
      HEADER('Every (authed) page of each console: [route, title, permission needed].') +
      `type PageRow = readonly [route: string, title: string, permission: string | null];\n\n${pageBlocks}`,
    'help-text.ts':
      HEADER(
        'Long help strings of each console, plus STAFF-ONLY settings guide and internal docs.',
      ) +
      `type TextRow = readonly [key: string, text: string];\n\n` +
      (Object.keys(portal) as Console[])
        .map((c) => rows(`PORTAL_TEXT_${c.toUpperCase()}`, 'ReadonlyArray<TextRow>', portal[c]))
        .join('\n') +
      '\n// STAFF ONLY below. Only the STAFF audience may ever be given these.\n' +
      rows('STAFF_SETTINGS_TEXT', 'ReadonlyArray<TextRow>', settings) +
      '\n' +
      rows('STAFF_INTERNAL_DOCS', 'ReadonlyArray<TextRow>', docs),
  };
}

/**
 * The files in `dir` whose bytes differ from what `render()` produces now
 * (a missing file counts). Empty means the committed indexes are fresh.
 */
export function staleFiles(rendered: GeneratedFiles, dir: string): string[] {
  return Object.entries(rendered)
    .filter(([file, body]) => {
      try {
        return readFileSync(join(dir, file), 'utf8') !== body;
      } catch {
        return true;
      }
    })
    .map(([file]) => file);
}
